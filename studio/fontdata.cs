using System;

internal static class CustomGlyphs
{
    // 8 个自定义槽位, 每槽 8 字节(行主序, 与 HD44780 CGRAM 一致: 每行 1 字节, bit0..4=列)
    public static readonly byte[][] Slot = new byte[8][];

    static CustomGlyphs()
    {
        for (int i = 0; i < 8; i++) Slot[i] = new byte[8];
        // 槽1 默认 = ℃ (圆环+C), 与 GUI/真屏一致
        Slot[1] = new byte[] { 0x0E, 0x0A, 0x0E, 0x0C, 0x02, 0x02, 0x0C, 0x00 };
    }

    public static string ToHex(int slot)
    {
        System.Text.StringBuilder sb = new System.Text.StringBuilder(16);
        foreach (byte b in Slot[slot]) sb.Append(b.ToString("X2"));
        return sb.ToString();
    }

    public static void SetFromHex(int slot, string hex)
    {
        if (hex == null || hex.Length < 16) return;
        for (int i = 0; i < 8; i++)
            Slot[slot][i] = Convert.ToByte(hex.Substring(i * 2, 2), 16);
    }

    /// <summary>槽位转 5 字节列主序(供模拟器绘制), bit0=顶行</summary>
    public static byte[] ToColumns(int slot)
    {
        byte[] g = new byte[5];
        for (int row = 0; row < 7; row++)
        {
            byte bits = Slot[slot][row];
            for (int col = 0; col < 5; col++)
                if ((bits & (1 << col)) != 0) g[col] |= (byte)(1 << row);
        }
        return g;
    }
}

