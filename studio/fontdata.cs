    /// <summary>取字符字模(超出 ASCII 可打印范围回退为下划线)</summary>
    public static byte[] Glyph(char c)
    {
        if (c >= 1 && c <= 8) return CustomGlyphs.ToColumns(c - 1);   // {g1}~{g8} 自定义槽位
        if (c == '\u00B0') return Degree;       // °
        if (c == '\u2103') return CustomGlyphs.ToColumns(1);          // ℃ = 槽1
        int i = (int)c;
        if (i < 32 || i > 126) i = (int)'_';
        byte[] g = new byte[CharW];
        Array.Copy(Data, (i - 32) * CharW, g, 0, CharW);
        return g;
    }

    // °: 3x3 圆环, 描绘在 0-2 行
    private static readonly byte[] Degree = new byte[] { 0x00, 0x07, 0x05, 0x07, 0x00 };
